#nullable enable
[RegisterPower]
public sealed class AdroitcapPower : ModPowerTemplate
{
    public override PowerAssetProfile AssetProfile => new(
        IconPath: $"res://Resource/Powers/River/{GetType().Name}128.png",
        BigIconPath: $"res://Resource/Powers/River/{GetType().Name}128.png"
    );

    public override PowerType Type => PowerType.Buff;

    public override PowerStackType StackType => PowerStackType.Counter;
    


    public override async Task AfterApplied(Creature? applier, CardModel? cardSource)
    {
    }

    public override async Task AfterPowerAmountChanged(PlayerChoiceContext choiceContext, PowerModel power, decimal amount, Creature? applier,
        CardModel? cardSource)
    {
        if(power.Owner==Owner&&power is  AdroitcapPower && amount > 0)
            await PowerCmd.Apply<AdroitPower>(choiceContext,Owner,amount,Owner,null);

    }


    public override async Task AfterPlayerTurnStart(PlayerChoiceContext choiceContext, Player player)
    {

        if (Owner == player.Creature&&Owner.CombatState?.RoundNumber!=1)
        {
            await PowerCmd.Apply<AdroitPower>(choiceContext,Owner,Amount,Owner,null);
            
        }

        

    }

}